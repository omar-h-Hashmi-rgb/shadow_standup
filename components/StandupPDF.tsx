interface StandupPDFProps {
  owner: string;
  repo: string;
  date: string;
  commits: number;
  content: string;
}

const SECTION_TITLES = [
  "Accomplishments",
  "Challenges and Blockers",
  "Technical Debt and Cleanups",
];

const parseSections = (content: string) => {
  const blocks = content.split(/\n\n+/).map((b) => b.trim()).filter(Boolean);
  return blocks.map((block) => {
    const lines = block.split("\n").map((line) => line.trim()).filter(Boolean);
    const title = lines[0] || "Section";
    const items = lines.slice(1).map((line) => line.replace(/^[-\s]+/, "")).filter(Boolean);
    return { title, items: items.length ? items : [block.replace(title, "").trim()].filter(Boolean) };
  });
};

export const StandupPDF = ({ owner, repo, date, commits, content }: StandupPDFProps) => {
  const sections = parseSections(content);

  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.title}>Shadow Standup Report</Text>
          <Text style={styles.subtitle}>AI-Generated Activity Summary</Text>
        </View>

        <View style={styles.metaSection}>
          <View style={styles.metaItem}>
            <Text style={styles.metaLabel}>Repository</Text>
            <Text style={styles.metaValue}>{owner}/{repo}</Text>
          </View>
          <View style={styles.metaItem}>
            <Text style={styles.metaLabel}>Date</Text>
            <Text style={styles.metaValue}>{new Date(date).toLocaleDateString()}</Text>
          </View>
          <View style={styles.metaItem}>
            <Text style={styles.metaLabel}>Commit Context</Text>
            <Text style={styles.metaValue}>{commits} Commits</Text>
          </View>
        </View>

        <View style={styles.content}>
          {sections.map((section, index) => (
            <View key={`${section.title}-${index}`}>
              <Text style={styles.sectionTitle}>{section.title}</Text>
              {section.items.map((item, itemIndex) => (
                <View key={`${section.title}-${itemIndex}`} style={styles.listItem}>
                  <Text style={styles.bullet}>•</Text>
                  <Text>{item}</Text>
                </View>
              ))}
            </View>
          ))}
        </View>

        <View style={styles.footer}>
          <Text style={styles.footerText}>Generated by Shadow Standup AI</Text>
          <Text style={styles.footerText}>Page 1 of 1</Text>
        </View>
      </Page>
    </Document>
  );
};
