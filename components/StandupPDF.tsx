import React from 'react';
import { Page, Text, View, Document, StyleSheet, Font } from '@react-pdf/renderer';

// Register a clean font (optional, using default Helvetica for simplicity if custom font not available)
// Standard fonts: Helvetica, Times-Roman, Courier, Symbol, ZapfDingbats

const styles = StyleSheet.create({
  page: {
    padding: 40,
    backgroundColor: '#FFFFFF',
    fontFamily: 'Helvetica',
  },
  header: {
    marginBottom: 30,
    borderBottomWidth: 2,
    borderBottomColor: '#2563EB',
    paddingBottom: 10,
  },
  title: {
    fontSize: 24,
    fontWeight: 'bold',
    color: '#111827',
  },
  subtitle: {
    fontSize: 10,
    color: '#6B7280',
    marginTop: 4,
    textTransform: 'uppercase',
    letterSpacing: 1,
  },
  metaSection: {
    flexDirection: 'row',
    justifyContent: 'space-between',
    marginBottom: 30,
    backgroundColor: '#F9FAFB',
    padding: 15,
    borderRadius: 8,
  },
  metaItem: {
    flexDirection: 'column',
  },
  metaLabel: {
    fontSize: 8,
    color: '#9CA3AF',
    textTransform: 'uppercase',
    marginBottom: 2,
  },
  metaValue: {
    fontSize: 10,
    color: '#374151',
    fontWeight: 'bold',
  },
  content: {
    fontSize: 11,
    lineHeight: 1.6,
    color: '#374151',
  },
  sectionTitle: {
    fontSize: 14,
    fontWeight: 'bold',
    color: '#111827',
    marginTop: 20,
    marginBottom: 10,
    textTransform: 'uppercase',
  },
  listItem: {
    flexDirection: 'row',
    marginBottom: 5,
    paddingLeft: 10,
  },
  bullet: {
    width: 10,
    fontSize: 11,
  },
  footer: {
    position: 'absolute',
    bottom: 40,
    left: 40,
    right: 40,
    borderTopWidth: 1,
    borderTopColor: '#E5E7EB',
    paddingTop: 10,
    flexDirection: 'row',
    justifyContent: 'space-between',
  },
  footerText: {
    fontSize: 8,
    color: '#9CA3AF',
  }
});

interface StandupPDFProps {
  owner: string;
  repo: string;
  date: string;
  commits: number;
  content: string;
}

export const StandupPDF = ({ owner, repo, date, commits, content }: StandupPDFProps) => {
  // Simple parsing of markdown-like sections
  const sections = content.split('\n\n');

  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.title}>Shadow Standup Report</Text>
          <Text style={styles.subtitle}>AI-Generated Activity Summary</Text>
        </View>

        <View style={styles.metaSection}>
          <View style={styles.metaItem}>
            <Text style={styles.metaLabel}>Repository</Text>
            <Text style={styles.metaValue}>{owner}/{repo}</Text>
          </View>
          <View style={styles.metaItem}>
            <Text style={styles.metaLabel}>Date</Text>
            <Text style={styles.metaValue}>{new Date(date).toLocaleDateString()}</Text>
          </View>
          <View style={styles.metaItem}>
            <Text style={styles.metaLabel}>Commit Context</Text>
            <Text style={styles.metaValue}>{commits} Commits</Text>
          </View>
        </View>

        <View style={styles.content}>
          {content.split('\n').map((line, index) => {
            if (line.trim().startsWith('###') || line.trim().startsWith('**')) {
              // Clean up markdown headers for PDF display
              const cleanTitle = line.replace(/[#*]/g, '').trim();
              return <Text key={index} style={styles.sectionTitle}>{cleanTitle}</Text>;
            }
            if (line.trim().startsWith('* ') || line.trim().startsWith('- ')) {
              return (
                <View key={index} style={styles.listItem}>
                  <Text style={styles.bullet}>•</Text>
                  <Text>{line.substring(2).trim()}</Text>
                </View>
              );
            }
            if (line.trim()) {
              return <Text key={index} style={{ marginBottom: 10 }}>{line.trim()}</Text>;
            }
            return null;
          })}
        </View>

        <View style={styles.footer}>
          <Text style={styles.footerText}>Generated by Shadow Standup AI</Text>
          <Text style={styles.footerText}>Page 1 of 1</Text>
        </View>
      </Page>
    </Document>
  );
};
