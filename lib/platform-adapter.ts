import type { StandupAnalysis } from "./prompts";

function escapeMrkdwn(text: string): string {
  return text.replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c] || c));
}

export function formatForSlack(analysis: StandupAnalysis): string {
  const cr = analysis.code_review;
  const lines: string[] = [
    `:rocket: *Shadow Standup Report*`,
    "",
    `*Developer:* ${analysis.developer} | *Repo:* \`${analysis.repository}\` | *Branch:* \`${analysis.branch}\``,
    "",
    `:memo: *Summary:*`,
    `${analysis.summary}`,
    "",
    `:white_check_mark: *Yesterday's Progress:*`,
    ...analysis.yesterday_progress.map((item) => `  • ${escapeMrkdwn(item)}`),
    "",
    `:bar_chart: *Code Review:*`,
    `  Complexity: *${cr.complexity_score}/10* | Health: *${cr.code_health}*`,
    ...cr.highlights.map((item) => `  • ${escapeMrkdwn(item)}`),
    "",
  ];

  if (analysis.blockers_and_risks.length > 0) {
    lines.push(
      `:warning: *Blockers & Risks:*`,
      ...analysis.blockers_and_risks.map((item) => `  • ${escapeMrkdwn(item)}`),
      ""
    );
  }

  if (cr.security_or_debt_flags.length > 0) {
    lines.push(
      `:rotating_light: *Security & Debt Flags:*`,
      ...cr.security_or_debt_flags.map((item) => `  • ${escapeMrkdwn(item)}`),
      ""
    );
  }

  if (analysis.today_focus.length > 0) {
    lines.push(
      `:dart: *Today's Focus:*`,
      ...analysis.today_focus.map((item) => `  • ${escapeMrkdwn(item)}`)
    );
  }

  return lines.join("\n");
}

const DISCORD_COLORS: Record<string, number> = {
  High: 3581519,
  Medium: 15910724,
  Low: 14687834,
};

export function formatForDiscord(analysis: StandupAnalysis): object {
  const cr = analysis.code_review;
  const color = DISCORD_COLORS[cr.code_health] || 15910724;

  const progressField = analysis.yesterday_progress.length > 0
    ? analysis.yesterday_progress.map((item) => `• ${item}`).join("\n")
    : "No items reported.";

  const focusField = analysis.today_focus.length > 0
    ? analysis.today_focus.map((item) => `• ${item}`).join("\n")
    : "No items planned.";

  const fields: Array<{ name: string; value: string; inline?: boolean }> = [
    {
      name: "Developer / Repository",
      value: `**${analysis.developer}**\n\`${analysis.repository}\` (${analysis.branch})`,
      inline: true,
    },
    {
      name: "Code Review Metrics",
      value: `**Complexity:** ${cr.complexity_score}/10\n**Health:** ${cr.code_health}`,
      inline: true,
    },
    {
      name: "Summary",
      value: analysis.summary,
    },
    {
      name: "Yesterday's Progress",
      value: progressField,
    },
    {
      name: "Today's Focus",
      value: focusField,
    },
  ];

  if (analysis.blockers_and_risks.length > 0) {
    fields.push({
      name: "Blockers & Risks",
      value: analysis.blockers_and_risks.map((item) => `⚠ ${item}`).join("\n"),
    });
  }

  if (cr.security_or_debt_flags.length > 0) {
    fields.push({
      name: "Security & Debt Flags",
      value: cr.security_or_debt_flags.map((item) => `🔴 ${item}`).join("\n"),
    });
  }

  return {
    username: "Shadow Standup Bot",
    embeds: [
      {
        title: "Shadow Standup Report",
        color,
        fields,
        footer: {
          text: "Generated by Shadow Standup AI",
        },
        timestamp: new Date().toISOString(),
      },
    ],
  };
}

export function formatForTrello(analysis: StandupAnalysis): { name: string; desc: string } {
  const cr = analysis.code_review;
  const desc = `# Standup: ${analysis.developer} - ${analysis.repository}
**Branch:** \`${analysis.branch}\`

### Executive Summary
${analysis.summary}

### Completed Items
${analysis.yesterday_progress.map((item) => `- ${item}`).join("\n") || "- None reported"}

### Today's Focus
${analysis.today_focus.map((item) => `- ${item}`).join("\n") || "- None planned"}

### Code Health & Review
- **Complexity Score:** ${cr.complexity_score}/10
- **Code Health:** ${cr.code_health}
- **Highlights:** ${cr.highlights.join("; ") || "None"}
- **Risks:** ${cr.risks.join("; ") || "None"}
- **Security & Debt:** ${cr.security_or_debt_flags.join("; ") || "None"}

### Blockers & Risks
${analysis.blockers_and_risks.map((item) => `- ${item}`).join("\n") || "- None"}`;

  return {
    name: `Standup: ${analysis.developer} - ${analysis.repository}`,
    desc,
  };
}

export function formatForJira(analysis: StandupAnalysis): string {
  const cr = analysis.code_review;
  const lines = [
    `h3. Shadow Standup Report - ${analysis.developer}`,
    `*Repository:* ${analysis.repository} | *Branch:* ${analysis.branch}`,
    "",
    `*Summary:* ${analysis.summary}`,
    "",
    `h4. Completed Items`,
    ...analysis.yesterday_progress.map((item) => `* ${item}`),
    "",
    `h4. Code Audit (Complexity: ${cr.complexity_score}/10)`,
    `* *Health:* ${cr.code_health}`,
    ...cr.highlights.map((item) => `* *Highlight:* ${item}`),
    ...cr.risks.map((item) => `* *Risk:* ${item}`),
    ...cr.security_or_debt_flags.map((item) => `* *Security/Debt:* ${item}`),
    "",
    `h4. Today's Focus`,
    ...analysis.today_focus.map((item) => `* ${item}`),
  ];

  if (analysis.blockers_and_risks.length > 0) {
    lines.push(
      "",
      `h4. Blockers & Risks`,
      ...analysis.blockers_and_risks.map((item) => `* ${item}`)
    );
  }

  return lines.join("\n");
}
